/**
 * Calcula a cor ideal do texto (preto ou branco) para contraste perfeito com base na luminância WCAG.
 */
export function getContrastTextColor(hexOrRgba?: string, fallbackDark: string = '#0f172a', fallbackLight: string = '#ffffff'): string {
  if (!hexOrRgba || hexOrRgba === 'transparent') return fallbackDark;

  let r = 255;
  let g = 255;
  let b = 255;

  if (hexOrRgba.startsWith('#')) {
    const hex = hexOrRgba.replace('#', '');
    if (hex.length === 3) {
      r = parseInt(hex[0] + hex[0], 16);
      g = parseInt(hex[1] + hex[1], 16);
      b = parseInt(hex[2] + hex[2], 16);
    } else if (hex.length >= 6) {
      r = parseInt(hex.substring(0, 2), 16);
      g = parseInt(hex.substring(2, 4), 16);
      b = parseInt(hex.substring(4, 6), 16);
    }
  } else if (hexOrRgba.startsWith('rgb')) {
    const match = hexOrRgba.match(/\d+/g);
    if (match && match.length >= 3) {
      r = parseInt(match[0], 10);
      g = parseInt(match[1], 10);
      b = parseInt(match[2], 10);
    }
  }

  // Luminância perceptiva WCAG
  const luminance = (0.299 * r + 0.587 * g + 0.114 * b) / 255;
  return luminance < 0.55 ? fallbackLight : fallbackDark;
}
